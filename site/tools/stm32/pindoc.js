  var FSMC_W = { sram: 16, nand: 8, lcd: 16 };
  function generic(m, p) {
    var name = String(p.name), net = p.net || '';
    if (net === 'GND' || /^(GND|VSS)$/.test(name)) return '地，也就是 0 V。所有信号的高低电平都是相对它来说的，电流最后都从地流回去。';
    if (net === 'NC' || name === 'NC') return '这个脚没有接任何东西，空着。';
    if (/^(VCC|VDD|3V3|5V)$/.test(name) || net === '3V3' || net === '5V') {
      var v = net === '5V' || name === '5V' ? '5 V' : '3.3 V';
      return '电源脚，给这颗芯片供 ' + v + ' 的电。旁边一般会放一颗小电容（100nF），像一个小水桶，芯片突然要用电时先从它这里取，让电压保持平稳。';
    }
    var sig = p.sig || '';
    if (!sig && m.id === 'lcd' && /^D\d+$/.test(name)) sig = 'FSMC_' + name;
    var d = /^FSMC_D(\d+)$/.exec(sig), a = /^FSMC_A(\d+)$/.exec(sig), w = FSMC_W[m.id] || 16;
    if (d) {
      if (m.id === 'lcd') return '屏幕的数据线第 ' + d[1] + ' 位。16 根数据线一起，一次传 16 位，正好是屏幕上一个点的颜色（红 5 位、绿 6 位、蓝 5 位）。单片机通过 FSMC 把屏幕当成内存来写，这些线由硬件自动控制，程序只管往地址里写数。';
      if (m.id === 'nand') return 'NAND 的数据线第 ' + d[1] + ' 位。8 根线一起一次传 1 个字节，命令、地址、数据都从这 8 根线走，靠 CLE、ALE 两个脚区分这个字节是什么。';
      return '数据线第 ' + d[1] + ' 位。' + w + ' 根数据线一起，一次能并排传 ' + (w === 16 ? '16 位（2 个字节）' : '8 位') + '，比一根线一位一位传快得多。读写时由 FSMC 硬件自动控制，程序像读写普通变量一样读写这块内存就行。';
    }
    if (a) return '地址线第 ' + a[1] + ' 位。SRAM 里有 512K 个小格子，19 根地址线每根是 0 或 1，组合起来就是一个格子的门牌号，告诉 SRAM 这次要读写哪个格子。由 FSMC 硬件自动控制。';
    return p.note || '';
  }
  function doc(m, p) {
    var x = D[m.id + '.' + p.k] || D[m.id + '.' + p.name];
    return { role: x || generic(m, p) };
  }
  STM.pindoc = doc;
  W.STM32_PINDOC = { doc: doc, table: D };
